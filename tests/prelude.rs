//! One glob import has to be enough: every trait whose method the workload calls,
//! every type a caller has to write down, plus the six exported macros (`all`,
//! `any`, `save`, `save_cache`, `load_cache`, `var_leaf`), arrive through
//! `express_it::prelude`.
//!
//! The last test pins the other half of the contract — the prelude is additive,
//! so the pre-existing full paths keep resolving and name the very same items.

use express_it::prelude::*;
use std::any::Any;
use std::collections::HashSet;

#[derive(Clone, Copy, Debug)]
struct State {
    hp: f32,
    atk: f32,
    def: f32,
    shield: f32,
}

struct Ctx;

impl Context for Ctx {
    type ContextItem<'w, 's> = State;
}

impl ContextMut for Ctx {
    type ContextItemMut<'w, 's> = State;

    fn as_readonly<'w, 's, 'a>(
        mut_item: &'a Self::ContextItemMut<'w, 's>,
    ) -> Self::ContextItem<'a, 's> {
        *mut_item
    }
}

fn hp() -> Node<f32, Ctx, VarExpr<f32, Ctx>> {
    Node::new(|state: &State| state.hp)
}

fn atk() -> Node<f32, Ctx, VarExpr<f32, Ctx>> {
    Node::new(|state: &State| state.atk)
}

fn def() -> Node<f32, Ctx, VarExpr<f32, Ctx>> {
    Node::new(|state: &State| state.def)
}

fn start() -> State {
    State {
        hp: 10.0,
        atk: 20.0,
        def: 5.0,
        shield: 0.0,
    }
}

// Two leaves for two attributes, generated by the sixth exported macro. Both the
// macro and the constructor have to be reachable from the one glob import at the
// top of this file: `var_leaf!` is re-exported, `Node::from_expr` is inherent.
// Neither leaf is named outside this module, so neither is given a visibility —
// the `vis` in the macro pattern matches an empty one, and the struct is private.
var_leaf!(HpLeaf, f32, Ctx, |state| state.hp);
var_leaf!(DefLeaf, f32, Ctx, |state| state.def);

#[test]
fn prelude_alone_builds_a_leaf_with_a_dependency_key_of_its_own() {
    let hp_leaf = Node::<f32, Ctx, _>::from_expr(HpLeaf);
    let def_leaf = Node::<f32, Ctx, _>::from_expr(DefLeaf);

    assert_eq!(hp_leaf.eval(&start()), 10.0);
    assert_eq!((hp_leaf + def_leaf).eval(&start()), 15.0);
    assert_eq!(def_leaf.to_string(), "DefLeaf");

    // The contrast the macro exists for: these two attributes are two keys, while
    // the `Node::new` helpers above (`hp()`, `def()`) report one key between them.
    let mut leaf_keys = HashSet::new();
    hp_leaf.get_dependencies(&mut leaf_keys);
    def_leaf.get_dependencies(&mut leaf_keys);
    assert_eq!(leaf_keys.len(), 2, "one key per attribute leaf");

    let mut var_keys = HashSet::new();
    hp().get_dependencies(&mut var_keys);
    def().get_dependencies(&mut var_keys);
    assert_eq!(var_keys.len(), 1, "and the shared VarExpr key unchanged");

    // The payoff the commit message promises, asserted on a composite built from
    // two macro leaves rather than on two merged single-leaf sets: the tree itself
    // reports two keys — through an arithmetic node, and through the comparison and
    // logic nodes too.
    let mut sum_keys = HashSet::new();
    (hp_leaf + def_leaf).get_dependencies(&mut sum_keys);
    assert_eq!(
        sum_keys.len(),
        2,
        "a composite of two var_leaf! attributes reports two dependency keys"
    );

    let mut condition_keys = HashSet::new();
    hp_leaf
        .lt(5.0)
        .and(def_leaf.gt(1.0))
        .get_dependencies(&mut condition_keys);
    assert_eq!(
        condition_keys.len(),
        2,
        "a boolean composite of the same two leaves reports those same two keys"
    );
}

#[test]
fn prelude_alone_supports_a_boolean_and_math_workload() {
    let state = start();

    // `any!`, `all!`, `.gt`, `.or`, `.and`, `.not`, `eval`.
    let cond = any![hp().gt(0.0), all![hp().lt(25.0), atk().gt(def())].not()];
    assert!(cond.eval(&state), "the first disjunct alone is enough");

    // `.max`, `.sqrt`, `.clamp`, `.abs`, `.powf`, `.acos`, unary `-`, `+`.
    assert_eq!((hp() + 1.0).max(25.0).sqrt().eval(&state), 5.0);
    assert_eq!(hp().clamp(20.0, 30.0).eval(&state), 20.0);
    assert_eq!((-hp()).abs().eval(&state), 10.0);
    assert_eq!(atk().powf(2.0).eval(&state), 400.0);
    assert!(
        def().acos().eval(&state).is_nan(),
        "acos of 5.0, out of the domain: the math traits are in scope and reach f32"
    );
}

#[test]
fn prelude_alone_supports_a_plan_built_with_the_three_step_macros() {
    let mut state = start();

    let plan = Plan::<Ctx>::new()
        .step(save!(
            State,
            shield,
            (atk() - def()).max(0.0),
            "shield_applied"
        ))
        .step(save_cache!("hp_after", hp()))
        .step(load_cache!(f32, "shield_applied"));

    plan.run(&mut state)
        .expect("every key the plan reads exists, so the run succeeds");
    assert_eq!(state.shield, 15.0);

    let err: PlanError = Plan::<Ctx>::new()
        .step(load_cache!(f32, "nobody_wrote_this"))
        .run(&mut state)
        .expect_err("a missing key is an Err, not a panic");
    assert!(matches!(err, PlanError::CacheMiss { .. }));
}

/// A step written by hand, named entirely through the prelude glob: `StepExecutor`,
/// `PlanCache`, `PlanError`, `CacheLookupStep`.
///
/// It delegates the read to a `CacheLookupStep`, which is also how it reports a
/// failure it did not detect: `PlanError`'s variants are `#[non_exhaustive]`, so
/// downstream code propagates the delegate's error instead of naming a variant.
/// The failure it detects for itself — a value it cannot write — is reported through
/// [`PlanError::step_value_mismatch`], the public constructor that exists for
/// exactly that case.
struct ShieldFromCache {
    lookup: CacheLookupStep<f32>,
}

impl StepExecutor<Ctx> for ShieldFromCache {
    fn evaluate(&self, ctx: &State, cache: &PlanCache) -> Result<Box<dyn Any>, PlanError> {
        // Qualified because `C` is only reachable through an associated type here.
        <_ as StepExecutor<Ctx>>::evaluate(&self.lookup, ctx, cache)
    }

    fn apply(
        &self,
        ctx: &mut State,
        value: Box<dyn Any>,
        _cache: &mut PlanCache,
    ) -> Result<(), PlanError> {
        // Under `Plan::run` the value always comes from this step's own `evaluate`,
        // so the downcast below succeeds. A hand-call with another type is still
        // reported: `PlanError::StepValueMismatch { .. }` cannot be written out here
        // (the variant is `#[non_exhaustive]`), but `step_value_mismatch` builds the
        // same value from outside the crate.
        let value = value.downcast::<f32>().map_err(|_| {
            PlanError::step_value_mismatch("ShieldFromCache", std::any::type_name::<f32>())
        })?;
        ctx.shield = *value;
        Ok(())
    }
}

#[test]
fn a_hand_written_step_reports_a_value_mismatch_through_the_public_constructor() {
    // The proof the constructor is sufficient: a step outside the crate cannot name
    // the variant, yet can report the mismatch instead of swallowing it. The value
    // is fed to `apply` by hand here because `Plan::run` always hands a step its own
    // `evaluate` output, which is why this path is unreachable through a run.
    let mut state = start();
    let mut cache = PlanCache::default();
    let shield = ShieldFromCache {
        lookup: CacheLookupStep::new("shield_seed"),
    };

    let err = <ShieldFromCache as StepExecutor<Ctx>>::apply(
        &shield,
        &mut state,
        Box::new(1i32),
        &mut cache,
    )
    .expect_err("a value this step cannot write must be an Err, not a silent no-op");

    let PlanError::StepValueMismatch {
        step: step_name,
        expected,
        ..
    } = err
    else {
        panic!("expected StepValueMismatch, got {err:?}");
    };
    assert_eq!(step_name, "ShieldFromCache");
    assert_eq!(expected, "f32");
    assert!(
        err.to_string().contains("ShieldFromCache"),
        "and the message names the step: {err}"
    );
    assert_eq!(
        state.shield, 0.0,
        "a rejected value must not be half-applied"
    );
}

#[test]
fn prelude_alone_supports_a_hand_written_step() {
    let mut state = start();

    let plan = Plan::<Ctx>::new()
        .step(save_cache!("shield_seed", (atk() - def()).max(0.0)))
        .step(ShieldFromCache {
            lookup: CacheLookupStep::new("shield_seed"),
        });

    plan.run(&mut state)
        .expect("the seed key was written by the step before");
    assert_eq!(state.shield, 15.0);
}

#[test]
fn a_hand_written_step_reports_a_miss_from_the_lookup_it_delegates() {
    let mut state = start();

    let err = Plan::<Ctx>::new()
        .step(ShieldFromCache {
            lookup: CacheLookupStep::new("nobody_wrote_this"),
        })
        .run(&mut state)
        .expect_err("the delegate's CacheMiss travels through the custom step");

    assert!(matches!(err, PlanError::CacheMiss { .. }));
    assert_eq!(state.shield, 0.0, "a failed run writes nothing");
}

#[test]
fn prelude_alone_names_a_cast_bound_and_the_three_step_types() {
    // The bound a generic cast helper needs, spelled with the prelude's `AsCast`.
    fn as_i32<T: AsCast<i32>>(value: T) -> i32 {
        value.as_cast()
    }

    fn as_u8<T: AsCast<u8>>(value: T) -> u8 {
        value.as_cast()
    }

    assert_eq!(as_i32(9.7f32), 9, "fraction dropped toward zero");
    assert_eq!(as_i32(1e30f64), i32::MAX, "float to int saturates");
    assert_eq!(as_u8(-1i32), 255, "int to int wraps on two's complement");
    assert_eq!(
        hp().cast::<i32>().eval(&start()),
        10,
        "and the node cast works"
    );

    // The three step types, named from the prelude rather than their home modules.
    let assignment: AssignmentStep<f32, _, _> = save!(State, shield, hp());
    let cache_save: CacheSaveStep<f32, Ctx, _> = save_cache!("k", hp());
    let lookup: CacheLookupStep<f32> = load_cache!(f32, "k");

    // Each one is a step this crate can run.
    let mut state = start();
    let plan = Plan::<Ctx>::new()
        .step(assignment)
        .step(cache_save)
        .step(lookup);
    plan.run(&mut state).expect("three plain steps must run");
    assert_eq!(state.shield, 10.0);
}

#[test]
fn existing_full_paths_still_resolve_and_name_the_same_items() {
    // Same trait, two spellings: a generic bounded on the prelude re-export only
    // typechecks when the re-export is the original item.
    fn via_prelude<T: ExprMax<f32>>(_value: &T) {}
    fn via_module_path<T: express_it::ops::ExprMax<f32>>(_value: &T) {}

    via_prelude(&hp());
    via_module_path(&hp());

    let _plan: express_it::plan::Plan<Ctx> = express_it::plan::Plan::<Ctx>::new();
    let _boxed: Option<express_it::expr::StoredExpr<f32, Ctx>> = None;
    let _bool_expr: Option<express_it::expr::BoolExpr<Ctx>> = None;
    let _alias: Option<express_it::nodes::Var<f32, Ctx>> = None;
    let _lookup: express_it::plan::CacheLookupStep<f32> = load_cache!(f32, "k");

    // Item 7 from the outside: plan steps clone even though `Ctx` is a plain unit
    // struct that is neither Clone nor Copy. The helper is generic so clippy's
    // `clone_on_copy` does not fire on the `Copy` case.
    fn cloned<T: Clone>(step: T) -> T {
        step.clone()
    }

    let _saved: express_it::nodes::CacheSaveStep<f32, Ctx, _> = cloned(save_cache!("k", hp()));
    let _assigned: express_it::plan::AssignmentStep<f32, _, _> = cloned(save!(State, shield, hp()));
}

/// The same macro, reached the same way (the glob at the top of this file does not
/// reach a nested module, so this one imports the prelude itself), generating one
/// leaf per visibility form: `pub`, `pub(crate)`, and no modifier at all.
///
/// The leaves live in a module so the outer test has to name the outward-facing
/// ones by path — that is what those two tokens are for — while the private one is
/// used from in here, which is the only place a private leaf can be used.
mod leaf_visibilities {
    use express_it::prelude::*;

    #[derive(Clone, Copy)]
    pub struct Nested {
        pub hp: f32,
        pub shield: f32,
    }

    pub struct NestedCtx;

    impl Context for NestedCtx {
        type ContextItem<'w, 's> = Nested;
    }

    var_leaf!(pub ShieldLeaf, f32, NestedCtx, |state| state.shield);
    var_leaf!(pub(crate) RegenLeaf, f32, NestedCtx, |state| state.hp / 2.0);
    var_leaf!(PrivateHpLeaf, f32, NestedCtx, |state| state.hp);

    #[test]
    fn a_leaf_with_no_visibility_modifier_works_inside_its_own_module() {
        let hp = Node::<f32, NestedCtx, _>::from_expr(PrivateHpLeaf);

        let nested = Nested {
            hp: 12.0,
            shield: 4.0,
        };
        assert_eq!(hp.eval(&nested), 12.0);
        assert_eq!(hp.to_string(), "PrivateHpLeaf");
    }
}

#[test]
fn the_prelude_macro_honours_pub_and_pub_crate_from_outside_the_module() {
    let nested = leaf_visibilities::Nested {
        hp: 12.0,
        shield: 4.0,
    };

    let shield =
        Node::<f32, leaf_visibilities::NestedCtx, _>::from_expr(leaf_visibilities::ShieldLeaf);
    let regen =
        Node::<f32, leaf_visibilities::NestedCtx, _>::from_expr(leaf_visibilities::RegenLeaf);

    assert_eq!(
        shield.eval(&nested),
        4.0,
        "the `pub` leaf is reachable by path"
    );
    assert_eq!(regen.eval(&nested), 6.0, "and so is the `pub(crate)` one");
    assert_eq!(shield.to_string(), "ShieldLeaf");
    assert_eq!(regen.to_string(), "RegenLeaf");
}
